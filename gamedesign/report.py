"""Phase 9: the design assessment report (Markdown) and implementation-ready specs for single proposals."""
from .evidence import LABEL

SEV = {"critical": "Critical", "major": "Major", "minor": "Minor", "info": "Note"}


def _loc(e):
    if not e.get("file"): return e.get("symbol") or ""
    return f"`{e['file']}" + (f":{e['line']}" if e.get("line") else "") + "`"


def assessment_md(A):
    g, S = A["game"], A["score"]
    props = {p["id"]: p for p in A["proposals"]}
    L = [f"# DESIGNCRAFT assessment: {g['title']}", "",
         f"Assessed {A['assessed_at'][:16].replace('T', ' ')} UTC · commit `{(g.get('commit') or 'unknown')[:10]}` · method `{A['method']}` · DESIGNCRAFT {A['designcraft_version']}", ""]
    if g.get("pitch"): L += [f"> {g['pitch']}", ""]
    L += ["## Overall", "", f"**{S['overall']} / 100** (ceiling {S['ceiling']} if every untested criterion were perfect) · coverage {round(S['coverage'] * 100)}% · confidence **{S['confidence']}**", "",
          S["note"], "", "| Category | Score | Ceiling | Coverage | Confidence |", "|---|---|---|---|---|"]
    for c in S["categories"].values():
        L.append(f"| {c['title']} | {c['score']} / {c['max']} | {c['ceiling']} | {round(c['coverage'] * 100)}% | {c['confidence']} |")
    cmp_ = A.get("compare")
    if cmp_:
        L += ["", f"Compared with run {cmp_['against']} ({cmp_['kind']}): overall {cmp_['overall']['from']} → {cmp_['overall']['to']} ({cmp_['overall']['delta']:+d}). {cmp_['note']}",
              f"Resolved findings: {len(cmp_['resolved'])} · new: {len(cmp_['new'])}"]
    L += ["", "## Evidence and limitations", "", f"Files read: {A['inspection']['files_read']} · design collections recognised: {len(A['inspection']['collections'])} · not recognised: {len(A['inspection']['unclassified'])}", ""]
    for l in A["inspection"]["limitations"]: L.append(f"- **{l['area']}**: {l['text']}")
    if A.get("playcraft"):
        pc = A["playcraft"]; L.append(f"- **PLAYCRAFT**: run {pc['run_id']} ({len(pc['criteria'])} automated-play criteria imported as *simulated* evidence).")
    else:
        L.append("- **PLAYCRAFT**: no recorded run for this game; nothing here is simulated or playtested.")
    L += ["", "Evidence levels: " + ", ".join(f"*{v}*" for v in LABEL.values()) + ". Inferred judgements are never presented as observed player behaviour.", ""]
    # priorities
    L += ["## Priorities", "", "Ranked by expected impact ÷ implementation complexity (best proposal per finding).", "", "| # | Finding | Severity | Best proposal | Complexity | Priority |", "|---|---|---|---|---|---|"]
    ranked = sorted([f for f in A["findings"] if f.get("proposals")], key=lambda f: -f["priority"])
    for i, f in enumerate(ranked[:15], 1):
        best = max((props[p] for p in f["proposals"] if p in props), key=lambda p: p["priority"])
        L.append(f"| {i} | {f['title']} | {SEV[f['severity']]} | {best['label']}: {best['proposal']} | {best['complexity']} | {best['priority']} |")
    # department sections
    for dk in A["departments_order"]:
        D = A["departments"][dk]
        L += ["", f"## {D['title']}", ""]
        if D.get("note"): L += [f"_{D['note']}_", ""]
        if D["strengths"]: L += ["**Working well**", ""] + [f"- {s}" for s in D["strengths"]] + [""]
        fs = [f for f in A["findings"] if f["dept"] == dk]
        if not fs: L.append("No findings."); continue
        for f in fs:
            L += [f"### {SEV[f['severity']]}: {f['title']}", "", f"{f['summary']}", "", f"*Why it matters:* {f['why']}", "",
                  f"*Claim level:* {LABEL[f['level']]}. Evidence:"]
            for e in f["evidence"][:6]: L.append(f"- [{LABEL[e['level']]}] {e['text']} {_loc(e)}")
            for pid in f.get("proposals", []):
                p = props.get(pid)
                if not p: continue
                L += ["", f"**{p['label']}: {p['proposal']}**", ""]
                L += [f"- {c}" for c in p["changes"]]
                L += [f"- *Expected experience (inferred):* {p['experience']}", f"- *Complexity:* {p['complexity']} ({p['complexity_why']})",
                      f"- *Trade-offs:* " + "; ".join(p["tradeoffs"]),
                      f"- *Validate:* {p['validation']['method']} Metric: {p['validation']['metric']}, now {p['validation']['current']}, target {p['validation']['target']}."]
            L.append("")
    L += ["", "---", "Generated by DESIGNCRAFT. The game repository was read, never modified or executed."]
    return "\n".join(L)


def spec_md(A, pid, notes=None):
    p = next((x for x in A["proposals"] if x["id"] == pid), None)
    if p is None:
        for ps in A.get("lab", {}).values():
            p = next((x for x in ps if x["id"] == pid), p)
    if p is None: raise KeyError(f"no proposal {pid}")
    f = next((x for x in A["findings"] if x["id"] == p.get("finding")), None)
    L = [f"# Design spec: {p['proposal']}", "", f"Game: {A['game']['title']} · proposal `{p['id']}` ({p['label']}) · from DESIGNCRAFT assessment {A.get('run_id') or A['assessed_at']}", "",
         "## Existing design (preserved)", "", p["existing"], "", "## Problem", "", p["problem"], "", "## Why it matters to players", "", p["why"], ""]
    if f:
        L += ["## Evidence", ""] + [f"- [{LABEL[e['level']]}] {e['text']} {_loc(e)}" for e in f["evidence"]] + [""]
    L += ["## Change", ""] + [f"{i}. {c}" for i, c in enumerate(p["changes"], 1)] + ["",
          "## Expected player experience (inferred until validated)", "", p["experience"], "",
          "## Implementation", "", f"Complexity: **{p['complexity']}** ({p['complexity_why']})", "", "Trade-offs:", ""] + [f"- {t}" for t in p["tradeoffs"]] + ["",
          "## Validation", "", f"- Metric: {p['validation']['metric']}", f"- Current: {p['validation']['current']}", f"- Target: {p['validation']['target']}", f"- Method: {p['validation']['method']}", "",
          "## Acceptance", "", "- [ ] Change implemented behind the existing design (original kept until validated)", "- [ ] DESIGNCRAFT re-run shows the metric at target",
          "- [ ] PLAYCRAFT pass recorded (simulated evidence)", "- [ ] Playtest notes recorded (playtested evidence)", ""]
    if notes: L += ["## Designer notes", ""] + [f"- {n}" for n in notes] + [""]
    L.append("No change to the game's source is made by DESIGNCRAFT; this spec is for a person (or Claude Code, with approval) to implement.")
    return "\n".join(L)
