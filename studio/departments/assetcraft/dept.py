"""AssetCraft: the universal asset layer over the studio catalogue (core/catalog.py, SQLite).
Every department run registers its outputs automatically; these actions scan existing projects,
search across all of them, find duplicates and unused files, trace dependencies, report licences
(and write ATTRIBUTION.md), re-verify hashes, bring the 3D library in, integrate assets into a project
(never overwriting without `replace`), and render a browsable HTML catalogue page."""
import html, json, os, shutil, base64
from core import catalog as C, validate as V
from core.contract import StudioError


def _json(ctx, name, data):
    p = ctx.path(name); json.dump(data, open(p, "w"), indent=1, default=str); return {"path": p, "role": "report", "format": "json"}


def scan(ctx, p):
    root = ctx.need(p["folder"]); rows, errors = C.scan(root, p.get("default_license"), project=os.path.abspath(p["project"]) if p.get("project") else None, formats=p.get("formats"))
    invalid = [r["rel"] for r in rows if not r["valid"]]
    by = {}
    for r in rows: by[r["kind"]] = by.get(r["kind"], 0) + 1
    return {"outputs": [_json(ctx, "scan.json", {"folder": root, "assets": len(rows), "by_kind": by, "invalid": invalid, "errors": errors})],
            "checks": [{"name": "assets catalogued", "ok": len(rows) > 0, "detail": by}, {"name": "every asset opens as its format", "ok": not invalid, "detail": invalid[:10]}],
            "catalogued": len(rows), "by_kind": by, "catalog": C.CATALOG}


def register(ctx, p):
    rows = [C.register(ctx.need(f), license=p.get("license"), attribution=p.get("attribution"), source={"type": "manual", "note": p.get("source")} if p.get("source") else None,
                       tags=p.get("tags")) for f in p["files"]]
    return {"outputs": [_json(ctx, "registered.json", rows)], "checks": [{"name": "registered", "ok": len(rows) == len(p["files"])}], "assets": rows}


def search(ctx, p):
    rows = C.search(p.get("query", ""), p.get("kind"), p.get("license"), p.get("project"), p.get("department"), p.get("history", False), p["limit"])
    return {"outputs": [_json(ctx, "search.json", rows)], "checks": [{"name": "search ran", "ok": True, "detail": len(rows)}], "results": len(rows),
            "assets": [{k: r[k] for k in ("id", "path", "kind", "format", "license", "version", "tags")} for r in rows[:50]]}


def get(ctx, p):
    r = C.get(p["asset"])
    if not r: raise StudioError(f"no asset {p['asset']} in the catalogue", hint="assetcraft_search or assetcraft_scan first")
    if p.get("dependencies"): r["dependencies"] = C.dependencies(r["path"])
    return {"outputs": [_json(ctx, f"asset_{r['id']}.json", r)], "checks": [{"name": "found", "ok": True}], "asset": r}


def duplicates(ctx, p):
    d = C.duplicates(p.get("project"), p["near"], p["threshold"])
    return {"outputs": [_json(ctx, "duplicates.json", d)], "checks": [{"name": "duplicate scan ran", "ok": True, "detail": {"exact_groups": len(d["exact"]), "near_groups": len(d["near"])}}], "duplicates": d}


def unused(ctx, p):
    proj = ctx.need(p["project"]); rows = C.unused(proj)
    total = sum(r["bytes"] for r in rows)
    return {"outputs": [_json(ctx, "unused.json", {"project": proj, "unused": rows, "bytes": total})],
            "checks": [{"name": "reference scan ran", "ok": True, "detail": {"unused": len(rows), "megabytes": round(total / 1e6, 2)}}], "unused": rows[:100]}


def dependencies(ctx, p):
    res = [C.dependencies(ctx.need(f)) for f in p["files"]]
    missing = {r["path"]: r.get("missing") for r in res if r.get("missing")}
    return {"outputs": [_json(ctx, "dependencies.json", res)], "checks": [{"name": "every dependency resolves", "ok": not missing, "detail": missing}], "dependencies": res}


def license_report(ctx, p):
    rep = C.license_report(p.get("project"))
    outs = [_json(ctx, "licenses.json", rep)]
    lines = ["# Asset attributions", "", f"Generated by GITCRAFT AssetCraft from the asset catalogue ({rep['total']} assets).", "", "| Licence | Assets |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in sorted(rep["by_license"].items())]
    if rep["attributions"]:
        lines += ["", "## Required attributions", ""] + [f"- `{a['path']}` — {a['attribution']}" for a in rep["attributions"]]
    if rep["unknown"]:
        lines += ["", "## Assets with no recorded licence", "", "Add a `<file>.license.json` sidecar ({\"license\": \"CC0-1.0\", \"attribution\": \"…\"}) and rescan.", ""] + [f"- `{u}`" for u in rep["unknown"][:200]]
    md = ctx.path("ATTRIBUTION.md"); open(md, "w").write("\n".join(lines) + "\n"); outs.append({"path": md, "role": "attribution", "format": "text"})
    checks = [{"name": "no non-commercial / no-derivatives assets", "ok": not rep["restricted"], "detail": {k: len(v) for k, v in rep["restricted"].items()}},
              {"name": "every asset has a licence", "ok": not rep["unknown"] or not p["require_known"], "detail": len(rep["unknown"])}]
    if rep["copyleft"]: ctx.note(f"copyleft/share-alike assets present: {', '.join(rep['copyleft'])}")
    return {"outputs": outs, "checks": checks, "licenses": {k: v for k, v in rep.items() if k not in ("unknown",)}}


def verify(ctx, p):
    r = C.verify(p.get("project"))
    return {"outputs": [_json(ctx, "verify.json", r)], "checks": [{"name": "every catalogued file is present and unchanged", "ok": not r["missing"] and not r["changed"],
                                                                    "detail": {"ok": r["ok"], "missing": r["missing"][:5], "changed": r["changed"][:5]}}], "verify": r}


def integrate(ctx, p):
    """Copy assets into a project folder (with their licence sidecar), hash-verified; refuses to overwrite
    an existing different file unless replace=true, and says what it replaced."""
    dest = os.path.abspath(p["dest"])
    from core import inside_roots
    if not inside_roots(dest): raise StudioError(f"GITCRAFT policy: {dest} is outside the workspace roots")
    os.makedirs(dest, exist_ok=True); done, replaced, skipped = [], [], []
    for a in p["assets"]:
        r = C.get(a) if (str(a).isdigit() or not os.path.exists(a)) else C.register(ctx.need(a))
        if not r: raise StudioError(f"no asset {a}")
        src = r["path"]; tgt = os.path.join(dest, os.path.basename(src))
        if os.path.exists(tgt) and C._sha(tgt) != r["sha256"]:
            if not p["replace"]: skipped.append({"asset": src, "reason": f"{tgt} exists with different content (replace=true to overwrite)"}); continue
            replaced.append({"path": tgt, "old_sha256": C._sha(tgt)})
        shutil.copy2(src, tgt)
        if C._sha(tgt) != r["sha256"]: raise StudioError(f"hash mismatch after copying {src}")
        side = {"license": r["license"], "attribution": r.get("attribution"), "source": r.get("source"), "sha256": r["sha256"], "catalog_id": r["id"]}
        json.dump(side, open(tgt + ".license.json", "w"), indent=1, default=str)
        n = C.register(tgt, license=r["license"], attribution=r.get("attribution"), source={"type": "integrated", "from": src, "catalog_id": r["id"]})
        done.append({"from": src, "to": tgt, "id": n["id"]})
    checks = [{"name": "assets integrated (hash-verified)", "ok": bool(done) or not p["assets"], "detail": len(done)}]
    if skipped: checks.append({"name": "nothing skipped", "ok": False, "detail": skipped})
    return {"outputs": [_json(ctx, "integrate.json", {"integrated": done, "replaced": replaced, "skipped": skipped})], "checks": checks, "integrated": done, "replaced": replaced}


def sync_3d(ctx, p):
    """Bring the shared 3D library (MeshCraft/ForgeCraft, assets/<id>/v<N>/asset.json) into the
    catalogue with each version's licence and provenance."""
    lib = ctx.need(p["library"]) if p.get("library") else (os.environ.get("GITCRAFT_3D_LIBRARY") or os.path.join(os.path.expanduser("~/.gitcraft"), "3d-library"))
    if not os.path.isdir(lib): raise StudioError(f"no 3D library at {lib}")
    n, versions = 0, 0
    for d, _, files in os.walk(lib):
        if "asset.json" not in files: continue
        try: md = json.load(open(os.path.join(d, "asset.json")))
        except Exception: continue
        if "files" not in md: continue
        versions += 1; lic = md.get("license") or {}
        spdx = lic.get("asset") if isinstance(lic, dict) else str(lic)
        tools = "; ".join(f"{t.get('tool')}: {t.get('license')}" for t in lic.get("tools", [])) if isinstance(lic, dict) else None
        for f in md["files"]:
            pth = os.path.join(d, f["path"])
            if os.path.exists(pth) and V.sniff(pth) in C.ASSET_FORMATS:
                C.register(pth, license=spdx or "see 3D library record", attribution=None,
                           source={"type": "3d-library", "asset": md.get("id"), "version": md.get("version"), "tool": md.get("tool"), "tools_licences": tools,
                                   "ai_generated": lic.get("ai_generated") if isinstance(lic, dict) else None}, tags=["3d-library", md.get("id") or ""])
                n += 1
    return {"outputs": [_json(ctx, "sync_3d.json", {"library": lib, "versions": versions, "registered": n})],
            "checks": [{"name": "3D library versions synced", "ok": versions > 0, "detail": {"versions": versions, "files": n}}], "registered": n}


def catalog_page(ctx, p):
    """A self-contained HTML catalogue (thumbnails inline) for browsing and sharing."""
    rows = [r for r in C.search(p.get("query", ""), p.get("kind"), None, p.get("project"), p.get("department"), False, p["limit"]) if r["exists"]]
    def thumb(r):
        if r.get("thumb") and os.path.exists(r["thumb"]): return "data:image/png;base64," + base64.b64encode(open(r["thumb"], "rb").read()).decode()
        return ""
    cards = "".join(f"""<div class="c"><div class="t">{f'<img src="{thumb(r)}">' if thumb(r) else '<span>' + html.escape(r['format']) + '</span>'}</div>
<b title="{html.escape(r['path'])}">{html.escape(os.path.basename(r['path']))}</b><small>{html.escape(r['kind'])} · {html.escape(r['format'])} · v{r['version']} · {r['bytes'] // 1024} KB</small>
<small class="l">{html.escape(r['license'] or 'UNKNOWN')}</small><small>{html.escape(', '.join(r['tags'][:3]))}</small></div>""" for r in rows)
    page = f"""<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Asset catalogue</title>
<style>body{{font:14px system-ui,sans-serif;margin:16px;background:#f5f6f8;color:#1c2230}}.g{{display:grid;grid-template-columns:repeat(auto-fill,minmax(170px,1fr));gap:12px}}
.c{{background:#fff;border-radius:8px;padding:8px;display:flex;flex-direction:column;gap:3px;box-shadow:0 1px 2px #0001}}.t{{height:120px;display:flex;align-items:center;justify-content:center;background:#e9ecf0;border-radius:6px;overflow:hidden}}
.t img{{max-width:100%;max-height:120px}}b{{font-size:13px;overflow:hidden;text-overflow:ellipsis;white-space:nowrap}}small{{color:#5b6475;font-size:11px}}.l{{color:#1f7a4c}}</style></head>
<body><h1>Asset catalogue <small>({len(rows)} assets)</small></h1><div class="g">{cards}</div><p><small>GITCRAFT AssetCraft · {html.escape(C.CATALOG)}</small></p></body></html>"""
    out = ctx.path((p.get("name") or "catalog") + ".html"); open(out, "w").write(page)
    return {"outputs": [{"path": out, "role": "catalog_page", "format": "html"}], "checks": [{"name": "assets listed", "ok": len(rows) > 0, "detail": len(rows)}]}


ACTIONS = {"scan": scan, "register": register, "search": search, "get": get, "duplicates": duplicates, "unused": unused, "dependencies": dependencies,
           "license_report": license_report, "verify": verify, "integrate": integrate, "sync_3d": sync_3d, "catalog_page": catalog_page}
