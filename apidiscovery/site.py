"""The static /apis/ page: apidiscovery/web/ plus one data file (data/apis.json).

The data file is the catalogue, the link checks merged in beside (never into) the catalogue's own fields, the lexicon,
and the statement and guide templates the page fills in, all generated here from the same Python the tools use, so the
page cannot say something the tools would not. The page loads the copy published with it first, then looks for a newer
one on the `api-catalog` branch (pushed by .github/workflows/api-catalog.yml) and uses it only when it is valid."""
import json, os, shutil
from . import HERE, SOURCE, VERSION, catalog, checks as CK, guide as G, intel, lexicon
from .search import W_NAME, W_CAT, W_DESC, W_SYN, W_USE

WEB = os.path.join(HERE, "web")
LIVE = "https://raw.githubusercontent.com/scottyfncodes/GITCRAFT/api-catalog/apis.json"
STATUSES = ("none", "reachable", "moved", "refused", "missing", "unreachable", "unreachable+")


def _fake_check(st):
    if st == "none": return None
    return {"status": st.rstrip("+"), "checked": "{{day}}", "final_host": "{{host}}", "http": "{{http}}", "error": "{{error}}" if st.endswith("+") else None}


def templates():
    """Every statement the page can show, generated by intel.assess / intel.summary / guide.guide with placeholders
    where an entry's own values go: {{name}} {{category}} {{description}} {{url}} {{day}} {{host}} {{http}} {{error}}
    {{header}} and, in code, {{label}} {{ENV}} {{Pascal}} {{snake}}."""
    T = {"label": "{{label}}", "env": "{{ENV}}", "pascal": "{{Pascal}}", "snake": "{{snake}}", "header": "{{header}}"}
    crit, summ, sect, code = {}, {}, {}, {}
    for a in ("none", "apiKey", "oauth", "header", "unknown"):
        for h in ("yes", "no", "unknown"):
            for c in ("yes", "no", "unknown"):
                e = {"id": "t", "name": "{{name}}", "category": "{{category}}", "description": "{{description}}", "url": "{{url}}", "auth": a, "auth_raw": "{{header}}", "https": h, "cors": c, "sponsored": False}
                for st in STATUSES:
                    ck = _fake_check(st)
                    crit[f"{a}|{h}|{c}|{st}"] = [[x["criterion"], x["finding"], x["basis"], x["tone"]] for x in intel.assess(e, ck)]
                    for sp in (0, 1):
                        summ[f"{a}|{h}|{c}|{st}|{sp}"] = intel.summary(dict(e, sponsored=bool(sp)), ck)
                for pf in ("server", "browser", "mobile"):
                    for st in ("ok", "bad"):
                        for lc, lang in (("js", "javascript"), ("other", "curl")):   # only JavaScript can be client code
                            g = G.guide(e, lang, pf, {"status": "{{status_text}}", "checked": "{{day}}"} if st == "bad" else None, _tokens=T)
                            sect[f"{a}|{h}|{c}|{pf}|{st}|{lc}"] = {"runs_on": g["runs_on"], "sections": [[s["title"], s["body"]] for s in g["sections"]]}
                    for lang in G.LANGS:
                        g = G.guide(e, lang, pf, _tokens=T)
                        code[f"{a}|{g['runs_on']}|{lang}"] = g["example"]["code"]
    # identical values are stored once
    def pack(d):
        vals, idx, keys = [], {}, {}
        for k, v in d.items():
            s = json.dumps(v, sort_keys=True)
            if s not in idx: idx[s] = len(vals); vals.append(v)
            keys[k] = idx[s]
        return {"keys": keys, "values": vals}
    return {"criteria": pack(crit), "summary": pack(summ), "sections": pack(sect), "code": pack(code), "status_text": CK.STATUS,
            "criteria_titles": intel.CRITERIA, "basis": intel.BASIS, "auth_label": intel.AUTH_LABEL, "languages": G.LANGS,
            "suitability": "Matches {{bits}}. Matched on the catalogue's one-line description, so confirm the endpoints you need in its documentation.",
            "unknown_note": "Pricing, limits, reliability and licence terms are unknown for all of them: those decide the choice, and only each provider's own pages answer them.",
            "method": "No scores: each cell is a statement with its basis. Catalogue values are public-apis' claims; only the documentation link is checked by this tool."}


def data(C=None, K=None):
    """The page's data file from a catalogue and a checks document."""
    C = C or catalog.load(); K = K or CK.load()
    entries = []
    for e in C["entries"]:
        ck = CK.for_entry(K, e)
        row = [e["id"], e["name"], e.get("description") or "", e["category"], e["url"], e["auth"], e.get("auth_raw") or "", e["https"], e["cors"], 1 if e.get("sponsored") else 0, e.get("also_in") or []]
        row.append([ck["status"], ck.get("http"), ck.get("final_host"), ck.get("error")] if ck else None)
        entries.append(row)
    return {"schema": 1, "tool": VERSION, "built": catalog.now(), "source": SOURCE,
            "catalogue": {"fetched": C.get("fetched"), "counts": C.get("counts"), "sha256": C.get("sha256")},
            "checks": {"checked": K.get("checked"), "counts": K.get("counts"), "of": K.get("of"), "method": K.get("method"), "means": K.get("means")},
            "categories": C.get("categories") or [], "fields": ["id", "name", "description", "category", "url", "auth", "auth_raw", "https", "cors", "sponsored", "also_in", "check"],
            "weights": {"name": W_NAME, "category": W_CAT, "description": W_DESC, "synonym": W_SYN, "use_case": W_USE},
            "lexicon": lexicon.export(), "templates": templates(), "entries": entries}


def publish(dist, C=None, K=None):
    """Write the page to dist (the Vercel build: forgecraft/ui/dist/apis). → the number of APIs published.
    A catalogue that cannot be read publishes the page with no entries and its reason, never a build failure."""
    if os.path.isdir(dist): shutil.rmtree(dist)
    shutil.copytree(WEB, dist)
    os.makedirs(os.path.join(dist, "data"), exist_ok=True)
    D = data(C, K)
    with open(os.path.join(dist, "data", "apis.json"), "w") as f: json.dump(D, f, ensure_ascii=False, separators=(",", ":"))
    return len(D["entries"])
